def glyph_bytes(ch):
    return [int(r.replace(".", "0").replace("#", "1"), 2) << 3 for r in G[ch]]


def width(s):
    return len(s) * FONTW


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    assert len(G) == 96
    out = ["; generated by art/font.py - 5x7 font, %d-pixel pitch, chars 32-127, rows 1-7" % FONTW,
           "FONTW   EQU %d" % FONTW, "font:"]
    for c in range(32, 128):
        assert glyph_bytes(chr(c))[0] == 0, chr(c)        # row 0 is always blank:
        out.append("        db " + ",".join("%d" % b for b in glyph_bytes(chr(c))[1:])   # store rows 1-7
                   + "   ; " + (repr(chr(c)) if c < 127 else "(c)"))
    open(os.path.join(here, "..", "src", "font.inc"), "w").write("\n".join(out) + "\n")

    from PIL import Image
    lines = ["THE PORTER'S LOGBOOK   Night 3 of 5",
             "In 1950 the Bishop bought the Tower. In",
             "September 1951 it opened as a boarding",
             "school for boys. 02:18  CAM 8  1-8 R",
             " !\"#$%&'()*+,-./0123456789:;<=>?@",
             "ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_`",
             "abcdefghijklmnopqrstuvwxyz{|}~\x7f"]
    im = Image.new("RGB", (256, 8 * len(lines)), (0, 0, 0))
    px = im.load()
    for li, s in enumerate(lines):
        for ci, ch in enumerate(s):
            for y, b in enumerate(glyph_bytes(ch)):
                for x in range(8):
                    if b & (0x80 >> x) and ci * FONTW + x < 256:
                        px[ci * FONTW + x, li * 8 + y] = (205, 205, 205)
    im.resize((im.width * 3, im.height * 3), Image.NEAREST).save(os.path.join(here, "font.png"))
    print("font.inc written (%d bytes)" % (96 * 7))
