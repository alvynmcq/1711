#!/usr/bin/env python3
"""Build 1711.tap: BASIC loader -> loading screen -> game code (128K only).

Runs the art and script steps first:
  art/font.py          -> src/font.inc
  art/prologue_art.py  -> art/*.scr
  art/portraits.py     -> art/*.bin (portraits, 10 x 12 characters)
  scripts/script.py    -> src/chunk*.inc (one per script chunk), src/pics.inc
  scripts/night.py 1   -> src/night.inc (Night One's statements and findings)
then assembles night.inc on its own at NBUF (as high under C000h as it
fits) and packs it with ZX0 into src/night.zx0; its labels go to
src/nightsym.inc for main.asm. Each script chunk is assembled on its own
at SBUF (as high under C000h as the largest fits) and packed the same way,
into src/scripts.inc with the chunk table. A chunk and the night are never
needed at once, so the two buffers may overlap.
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
ORG = 0x6000

for cmd, cwd in ((["font.py"], "art"), (["prologue_art.py"], "art"),
                 (["portraits.py"], "art"), (["script.py"], "scripts"),
                 (["night.py", "1"], "scripts")):
    subprocess.run([sys.executable] + cmd, cwd=os.path.join(ROOT, cwd), check=True,
                   stdout=subprocess.DEVNULL)

os.chdir(os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "art"))
from zx0 import compress  # noqa: E402


def night_blob(org):
    """Assemble night.inc on its own at org; return the bytes and its labels."""
    open("nightblob.asm", "w").write(
        "; generated by build.py\n        ORG %d\n        INCLUDE \"night.inc\"\n" % org)
    subprocess.run(["pasmo", "--bin", "nightblob.asm", "nightblob.bin", "nightblob.sym"],
                   check=True)
    return open("nightblob.bin", "rb").read(), open("nightblob.sym").read()


# The night's text and tables are assembled at NBUF, as high as they fit
# under C000h, packed with ZX0 into the code, and unpacked there by `night`.
blob, _ = night_blob(0x8000)
NBUF = (0xC000 - len(blob)) & 0xFF00
blob, sym = night_blob(NBUF)
packed = compress(blob)
open("night.zx0", "wb").write(packed)
open("nightsym.inc", "w").write("; generated by build.py from night.inc\nNBUF EQU %d\n" % NBUF + sym)



def chunk_blob(n, org):
    open("chunkblob.asm", "w").write(
        "; generated by build.py\n        ORG %d\n        INCLUDE \"chunk%d.inc\"\n" % (org, n))
    subprocess.run(["pasmo", "--bin", "chunkblob.asm", "chunkblob.bin"], check=True)
    return open("chunkblob.bin", "rb").read()


# The scripts (title, prologue, ...) are chunks, packed with ZX0 and
# unpacked to SBUF by LOAD.
names = open("chunks.txt").read().split()
SBUF = (0xC000 - max(len(chunk_blob(n, 0x8000)) for n in range(len(names)))) & 0xFF00
out = ["; generated by build.py: the script chunks, ZX0, unpacked to SBUF",
       "SBUF EQU %d" % SBUF, "chunktab: dw " + ",".join("chunkz%d" % n for n in range(len(names)))]
sizes = []
for n, name in enumerate(names):
    raw = chunk_blob(n, SBUF)
    z = compress(raw)
    sizes.append((name, len(raw), len(z)))
    out.append("chunkz%d:   ; %s, %d bytes, %d packed" % (n, name, len(raw), len(z)))
    for k in range(0, len(z), 24):
        out.append("        db " + ",".join(str(b) for b in z[k:k + 24]))
open("scripts.inc", "w").write("\n".join(out) + "\n")

subprocess.run(["pasmo", "--bin", "main.asm", "main.bin", "main.sym"], check=True)
code = open("main.bin", "rb").read()
end = ORG + len(code)
low = min(NBUF, SBUF)
PSCR = 10 * 12 * 9                                   # a portrait, unpacked (main.asm)
assert end + PSCR <= low, "code + portrait scratch must stay below the buffers at %04Xh (ends %04Xh)" % (
    low, end + PSCR)
print("night: %d bytes at %04Xh-BFFFh, %d packed" % (len(blob), NBUF, len(packed)))
print("scripts: %d chunks at %04Xh, %d bytes, %d packed (%s)" % (
    len(names), SBUF, sum(r for _, r, _ in sizes), sum(z for _, _, z in sizes),
    ", ".join("%s %d" % (nm, r) for nm, r, _ in sizes)))

# loading screen: the house, rows 14-23 blank
screen = bytearray(open(os.path.join(ROOT, "art", "house.scr"), "rb").read())


def num(n):
    return str(n).encode() + bytes([0x0E, 0, 0, n & 255, n >> 8, 0])


BORDER, PAPER, INK, CLEAR, LOAD, SCREEN, POKE, CODE, RANDOMIZE, USR = \
    0xE7, 0xDA, 0xD9, 0xFD, 0xEF, 0xAA, 0xF4, 0xAF, 0xF9, 0xC0
line = (bytes([BORDER]) + num(0) + b":" + bytes([PAPER]) + num(0) + b":" +
        bytes([INK]) + num(7) + b":" + bytes([CLEAR]) + num(ORG - 1) + b":" +
        bytes([LOAD]) + b'""' + bytes([SCREEN]) + b":" +
        bytes([POKE]) + num(23739) + b"," + num(111) + b":" +
        bytes([LOAD]) + b'""' + bytes([CODE]) + b":" +
        bytes([RANDOMIZE, USR]) + num(ORG) + b"\r")
basic = bytes([0, 10]) + len(line).to_bytes(2, "little") + line


def block(flag, data):
    chk = flag
    for b in data:
        chk ^= b
    body = bytes([flag]) + data + bytes([chk])
    return len(body).to_bytes(2, "little") + body


def header(kind, name, length, p1, p2):
    return block(0, bytes([kind]) + name.ljust(10).encode() +
                 length.to_bytes(2, "little") + p1.to_bytes(2, "little") + p2.to_bytes(2, "little"))


tap = (header(0, "1711", len(basic), 10, len(basic)) + block(0xFF, basic) +
       header(3, "screen", 6912, 16384, 32768) + block(0xFF, bytes(screen)) +
       header(3, "1711", len(code), ORG, 32768) + block(0xFF, code))
open(os.path.join(ROOT, "1711.tap"), "wb").write(tap)
print("1711.tap: %d bytes; code %d bytes, %04Xh-%04Xh, portrait scratch %04Xh (%d free below the buffers)"
      % (len(tap), len(code), ORG, end - 1, end, low - end - PSCR))
