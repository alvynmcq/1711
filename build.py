#!/usr/bin/env python3
"""Build 1711.tap: BASIC loader -> loading screen -> game code -> the banks
(128K only).

Runs the art and script steps first:
  art/font.py          -> src/font.inc
  art/prologue_art.py  -> art/*.scr
  art/portraits.py     -> art/*.bin (portraits, each its own size; a
                          witness's falter cells, art/*_falter.bin)
  scripts/script.py    -> src/chunk*.inc (one per script chunk), src/pics.inc,
                          src/port_*.inc
  scripts/trial.py     -> src/trialc.inc (the day's common tables, below
                          C000h) and src/trialw_ID.inc (a witness; v1.0)
then builds the bank images at C000h (v0.7; v1.0):
  bank 1     the script buffer SBUF, the chunks packed with ZX0, the
             prologue pictures and the portraits shown from scripts (Isobel)
  banks 3-6  the witnesses, read in place while each is in the box, each
             with its portrait and falter cells, as many to a bank as fit
  bank 7     the trial's pictures
writes src/banks.inc (the chunk, picture, portrait and witness tables as
bank and address, and the boot stub's load table) and assembles
src/main.asm. On the tape each bank follows the code as a headerless block,
packed when that saves room.
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
ORG = 0x6000

for cmd, cwd in ((["font.py"], "art"), (["prologue_art.py"], "art"),
                 (["portraits.py"], "art"), (["script.py"], "scripts"),
                 (["trial.py"], "scripts")):
    subprocess.run([sys.executable] + cmd, cwd=os.path.join(ROOT, cwd), check=True,
                   stdout=subprocess.DEVNULL)

os.chdir(os.path.join(ROOT, "src"))
sys.path.insert(0, os.path.join(ROOT, "art"))
from zx0 import compress  # noqa: E402

# ---- the banks (v0.7; v1.0: the trial over several) ----
# Each bank is paged in at C000h. FDFDh-FFFFh is the IM2 jump and table in
# every bank (written by the boot stub), and PSCR, the portrait scratch, sits
# under it in any bank that holds a portrait. A bank's image is assembled at
# C000h; what goes on the tape is the image from its first byte of data
# (anything before it is a buffer), packed with ZX0 when that saves room.
# The stub loads a packed image high in its bank and unpacks it in place.
IM2TOP = 0xFDFD                 # first byte of the IM2 jump + table
PSCRLEN = 2 + 16 * 14 * 9      # portrait scratch: the largest, 16 x 14 (v0.9)
PSCR = 0xF5E0                   # under the IM2 jump and table
assert PSCR + PSCRLEN <= IM2TOP
SCRIPTBANK = 1                  # bank 1: scripts, the prologue's pictures, Isobel
WBANKS = [3, 4, 6]              # the witnesses, each with its portrait, in turn
WFILL = 7000                    # at most this much a bank, so each packs in place
PICBANK = 7                     # the trial's pictures (v1.0)
PIC_BANK = {"house": 1, "window": 1, "grave": 1,
            "court": PICBANK, "dock": PICBANK, "isobel_in": PICBANK, "pillory": PICBANK}


def asm(name, text):
    """Assemble text; return its bytes and labels (name -> value)."""
    open(name + ".asm", "w").write("; generated by build.py\n" + text)
    subprocess.run(["pasmo", "--bin", name + ".asm", name + ".bin", name + ".sym"], check=True)
    syms = {}
    for ln in open(name + ".sym"):
        w = ln.split()
        if len(w) == 3 and w[1] == "EQU":
            syms[w[0]] = int(w[2].rstrip("Hh"), 16)
    return open(name + ".bin", "rb").read(), syms


def chunk_blob(n, org):
    return asm("chunkblob", "        ORG %d\n        INCLUDE \"chunk%d.inc\"\n" % (org, n))[0]


portraits = open("portraits.txt").read().split()
pics = open("pics.txt").read().split()
witnesses = [ln.split() for ln in open("witnesses.txt").read().splitlines() if ln.strip()]
for p in pics:
    assert p in PIC_BANK, "picture %s has no bank (PIC_BANK in build.py)" % p
PORT_BANK = {"isobel": SCRIPTBANK}

# The witnesses: each with its portrait, packed into WBANKS in order, up to
# WFILL bytes a bank (a fuller bank can't be unpacked in place, and goes on
# the tape raw).
WITNESS_BANK, wb, used = {}, 0, 0
for wid, port in witnesses:
    size = len(asm("wsize", "        ORG 0C000h\n        INCLUDE \"trialw_%s.inc\"\n"
                   "        INCLUDE \"port_%s.inc\"\n" % (wid, port))[0])
    if used + size > WFILL:
        wb, used = wb + 1, 0
        assert wb < len(WBANKS), "the witnesses don't fit in banks %s" % WBANKS
    WITNESS_BANK[wid] = WBANKS[wb]
    PORT_BANK[port] = WBANKS[wb]
    used += size
for p in portraits:
    assert p in PORT_BANK, "portrait %s has no bank" % p


def ports_in(bank):
    return "".join("        INCLUDE \"port_%s.inc\"\n" % p for p in portraits if PORT_BANK[p] == bank)


def pics_in(bank):
    return "".join("        INCLUDE \"pic_%s.inc\"\n" % p for p in pics if PIC_BANK[p] == bank)


# Bank 1: the script buffer SBUF at C000h (not on the tape), then the
# packed chunks, the prologue pictures and the portraits shown from scripts.
names = open("chunks.txt").read().split()
SBUF = 0xC000
SBUFLEN = max(len(chunk_blob(n, SBUF)) for n in range(len(names)))
out, sizes = [], []
for n, name in enumerate(names):
    raw = chunk_blob(n, SBUF)
    z = compress(raw)
    sizes.append((name, len(raw), len(z)))
    out.append("chunkz%d:   ; %s, %d bytes, %d packed" % (n, name, len(raw), len(z)))
    for k in range(0, len(z), 24):
        out.append("        db " + ",".join(str(b) for b in z[k:k + 24]))
open("scripts.inc", "w").write("; generated by build.py: the script chunks, ZX0, unpacked to SBUF\n"
                               + "\n".join(out) + "\n")
images = {}       # bank -> (image, symbols, first byte of data, end)
b1, b1sym = asm("bank1", "        ORG %d\nSBUF:   ds %d\nb_data:\n"
                "        INCLUDE \"scripts.inc\"\n%s%sb_end:\n"
                % (SBUF, SBUFLEN, pics_in(SCRIPTBANK), ports_in(SCRIPTBANK)))
images[SCRIPTBANK] = (b1, b1sym, b1sym["b_data"], b1sym["b_end"])

# The witnesses' banks: each witness read in place while it is in the box
# (trial.asm pages its bank in), its portrait after it.
for bank in sorted(set(WITNESS_BANK.values())):
    inc = "".join("        INCLUDE \"trialw_%s.inc\"\n" % w for w, _ in witnesses if WITNESS_BANK[w] == bank)
    img, sym = asm("bank%d" % bank, "        ORG 0C000h\nb_data:\n%s%sb_end:\n" % (inc, ports_in(bank)))
    images[bank] = (img, sym, 0xC000, sym["b_end"])

# The trial's pictures.
img, sym = asm("bank%d" % PICBANK, "        ORG 0C000h\nb_data:\n%sb_end:\n" % pics_in(PICBANK))
images[PICBANK] = (img, sym, 0xC000, sym["b_end"])

banks = []        # (bank, image from its data, address of the data, limit)
for bank in sorted(images):
    img, sym, start, top = images[bank]
    data = img[start - 0xC000:top - 0xC000]
    limit = PSCR if any(PORT_BANK[p] == bank for p in portraits) else IM2TOP
    assert top <= limit, "bank %d is full: ends %04Xh, limit %04Xh" % (bank, top, limit)
    banks.append((bank, data, start, limit))


def where(label):
    for bank, (img, sym, start, top) in images.items():
        if label in sym:
            return bank, sym[label]
    raise KeyError(label)


# The tables below C000h: chunks, pictures, portraits and witnesses as
# (bank, address).
def tab(label, entries):
    return "%s:\n" % label + "".join("        db %d\n        dw %d\n" % e for e in entries)


tables = ["; generated by build.py: where everything is, bank and address",
          "SBUF    EQU %d" % SBUF, "PSCR    EQU %d" % PSCR,
          "SCRIPTBANK EQU %d" % SCRIPTBANK,
          tab("chunktab", [(SCRIPTBANK, b1sym["chunkz%d" % n]) for n in range(len(names))]),
          tab("pictab", [where("pic_" + p) for p in pics]),
          tab("porttab", [where("port_" + p) for p in portraits]),
          tab("witab", [where("wh_" + w) for w, _ in witnesses])]

# The boot stub's load table: a block per bank in tape order, as
# (7FFDh value, where it loads, length, where it unpacks or 0 if raw).
blocks, btab = [], []
for bank, data, start, limit in banks:
    z = compress(data)
    at = IM2TOP - len(z)
    if len(z) + 256 < len(data) and start + len(data) <= at:   # else raw: too full to unpack in place
        blocks.append(z)
        btab.append((0x10 | bank, at, len(z), start))
    else:
        blocks.append(data)
        btab.append((0x10 | bank, start, len(data), 0))
tables.append("B_tab:\n" + "".join("        db %d\n        dw %d,%d,%d\n" % e for e in btab) + "        db 0")
open("banks.inc", "w").write("\n".join(tables) + "\n")

subprocess.run(["pasmo", "--bin", "main.asm", "main.bin", "main.sym"], check=True)
code = open("main.bin", "rb").read()
end = ORG + len(code)
assert end <= 0xC000, "the code must stay below C000h (ends %04Xh)" % end
print("bank %d: scripts at %04Xh (%d chunks, %d bytes, %d packed: %s), %s, %s; ends %04Xh" % (
    SCRIPTBANK, SBUF, len(names), sum(r for _, r, _ in sizes), sum(z for _, _, z in sizes),
    ", ".join("%s %d" % (nm, r) for nm, r, _ in sizes),
    ", ".join(p for p in pics if PIC_BANK[p] == SCRIPTBANK),
    ", ".join(p for p in portraits if PORT_BANK[p] == SCRIPTBANK) or "no portraits", b1sym["b_end"]))
for bank in sorted(set(WITNESS_BANK.values())):
    print("bank %d: witnesses %s; ends %04Xh" % (
        bank, ", ".join(w for w, _ in witnesses if WITNESS_BANK[w] == bank), images[bank][3]))
print("bank %d: pictures %s; ends %04Xh" % (
    PICBANK, ", ".join(p for p in pics if PIC_BANK[p] == PICBANK), images[PICBANK][3]))
for (bank, data, start, limit), (_, at, ln, unp) in zip(banks, btab):
    print("  tape block for bank %d: %d bytes%s, %d free in the bank" % (
        bank, ln, " packed (%d unpacked)" % len(data) if unp else " raw", limit - start - len(data)))

# loading screen: the house, rows 14-23 blank
screen = bytearray(open(os.path.join(ROOT, "art", "house.scr"), "rb").read())


def num(n):
    return str(n).encode() + bytes([0x0E, 0, 0, n & 255, n >> 8, 0])


BORDER, PAPER, INK, CLEAR, LOAD, SCREEN, POKE, CODE, RANDOMIZE, USR = \
    0xE7, 0xDA, 0xD9, 0xFD, 0xEF, 0xAA, 0xF4, 0xAF, 0xF9, 0xC0
line = (bytes([BORDER]) + num(0) + b":" + bytes([PAPER]) + num(0) + b":" +
        bytes([INK]) + num(7) + b":" + bytes([CLEAR]) + num(ORG - 1) + b":" +
        bytes([LOAD]) + b'""' + bytes([SCREEN]) + b":" +
        bytes([POKE]) + num(23739) + b"," + num(111) + b":" +
        bytes([LOAD]) + b'""' + bytes([CODE]) + b":" +
        bytes([RANDOMIZE, USR]) + num(ORG) + b"\r")
basic = bytes([0, 10]) + len(line).to_bytes(2, "little") + line


def block(flag, data):
    chk = flag
    for b in data:
        chk ^= b
    body = bytes([flag]) + data + bytes([chk])
    return len(body).to_bytes(2, "little") + body


def header(kind, name, length, p1, p2):
    return block(0, bytes([kind]) + name.ljust(10).encode() +
                 length.to_bytes(2, "little") + p1.to_bytes(2, "little") + p2.to_bytes(2, "little"))


tap = (header(0, "1711", len(basic), 10, len(basic)) + block(0xFF, basic) +
       header(3, "screen", 6912, 16384, 32768) + block(0xFF, bytes(screen)) +
       header(3, "1711", len(code), ORG, 32768) + block(0xFF, code) +
       b"".join(block(0xFF, b) for b in blocks))
open(os.path.join(ROOT, "1711.tap"), "wb").write(tap)
print("1711.tap: %d bytes; code %d bytes, %04Xh-%04Xh, %d free below C000h"
      % (len(tap), len(code), ORG, end - 1, 0xC000 - end))
